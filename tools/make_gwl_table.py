# Build data/gwl_windows_ar6_ssp585.csv from the IPCC AR6 warming-level table
# (Hauser, Engelbrecht & Fischer, doi:10.5281/zenodo.3591806;
#  github.com/mathause/cmip_warming_levels,
#  warming_levels/cmip6_all_ens/csv/cmip6_warming_levels_all_ens_1850_1900.csv).
# Keeps SSP5-8.5 rows for the exact model + member CCKP downscaled.
# Usage: python tools/make_gwl_table.py <hauser_csv> data/gwl_windows_ar6_ssp585.csv
import csv
import sys
sys.path.insert(0, '.')
import analog_config as cfg

src, dst = sys.argv[1], sys.argv[2]
rows = [l for l in open(src) if not l.startswith('#')]
out = []
for r in csv.DictReader(rows, skipinitialspace=True):
    m = r['model'].lower()
    if r['exp'] != 'ssp585' or cfg.MODELS.get(m) != r['ensemble']:
        continue
    out.append((m, r['ensemble'], float(r['warming_level']),
                int(r['start_year']), int(r['end_year'])))
out.sort(key=lambda x: (x[2], x[0]))
with open(dst, 'w') as f:
    f.write('# GWL windows (20-yr, inclusive) relative to 1850-1900, SSP5-8.5.\n')
    f.write('# Source: IPCC AR6 Atlas warming levels, Hauser et al. (zenodo 3591806),\n')
    f.write(f'# file {src.split("/")[-1]}. Generated by tools/make_gwl_table.py.\n')
    f.write('model,ensemble,warming_level,start_year,end_year\n')
    for r in out:
        f.write(f'{r[0]},{r[1]},{r[2]},{r[3]},{r[4]}\n')
print(f'{len(out)} rows -> {dst}')
